import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { before,after,describe,test } from 'node:test';
import { Browser } from '../e2ee/support/dataApp.ts';
import { DataStack,delay } from './support/stack.ts';
describe('authenticated reactions preserve E2EE and one reaction per participant',()=>{
  let stack:DataStack;
  before(async()=>{stack=await DataStack.start();});after(async()=>{await stack?.close();});
  const intent=(emoji:string|null,expectedRevision:number)=>({emoji,expectedRevision,operationId:randomUUID()});
  test('two participants add concurrently, aggregate, replace/remove independently and replay operations without resurrection',async()=>{
    const {alice,bob,conversationId,epoch}=await stack.pair();
    const original=(await alice.browser.mutate('POST',`/api/conversations/${conversationId}/messages`,await stack.envelope(alice,conversationId,epoch,'Private E2EE text 👩🏽‍💻','__proto__'))).body.message;
    const a=await stack.connect(alice),b=await stack.connect(bob),mark=a.mark(),bmark=b.mark(),route=`/api/messages/${original.storageId}/reaction`;
    const first=intent('👍',0);
    const results=await Promise.all([alice.browser.mutate('POST',route,first),bob.browser.mutate('POST',route,intent('👍',0))]);
    assert.deepEqual(results.map(r=>r.status),[200,200]);
    assert.deepEqual(await a.waitFor('message:reactions-changed',()=>true,{since:mark}),{conversationId,messageId:original.id});
    assert.deepEqual(await b.waitFor('message:reactions-changed',()=>true,{since:bmark}),{conversationId,messageId:original.id});
    const list=async()=> (await bob.browser.request(`/api/conversations/${conversationId}/reactions?ids=${original.storageId}`)).body.items[0];
    let snapshot=await list();assert.equal(snapshot.version,2);assert.equal(snapshot.actors.filter((r:{emoji:string})=>r.emoji==='👍').length,2);
    assert.equal((await alice.browser.mutate('POST',route,intent('👩🏽‍💻',1))).status,200);
    assert.equal((await bob.browser.mutate('POST',route,intent(null,1))).status,200);
    snapshot=await list();assert.equal(snapshot.version,4);assert.equal(snapshot.actors.find((r:{userId:string})=>r.userId===alice.id).emoji,'👩🏽‍💻');
    assert.equal(snapshot.actors.find((r:{userId:string})=>r.userId===bob.id).emoji,null);
    assert.deepEqual((await alice.browser.mutate('POST',route,first)).body,results[0].body);
    assert.equal((await list()).version,4);assert.equal((await alice.browser.mutate('POST',route,{...first,emoji:'🔥'})).status,409);
    assert.equal((await alice.browser.mutate('POST',route,intent('🔥',1))).status,409);
    assert.deepEqual((await stack.history(bob,conversationId)).items,[original]);
    assert.ok(!JSON.stringify(snapshot).includes('Private E2EE'));
  });
  test('same-account concurrent changes conflict, duplicate requests are idempotent, and Unsend clears all reactions',async()=>{
    const {alice,bob,conversationId,epoch}=await stack.pair('race-a','race-b');
    const original=(await alice.browser.mutate('POST',`/api/conversations/${conversationId}/messages`,await stack.envelope(alice,conversationId,epoch,'Original immutable bytes'))).body.message;
    const route=`/api/messages/${original.storageId}/reaction`,same=intent('❤️',0);
    const duplicates=await Promise.all([alice.browser.mutate('POST',route,same),alice.browser.mutate('POST',route,same)]);
    assert.equal(duplicates[0].status,200);assert.deepEqual(duplicates[0].body,duplicates[1].body);
    const race=await Promise.all([alice.browser.mutate('POST',route,intent('🔥',1)),alice.browser.mutate('POST',route,intent('😂',1))]);
    assert.deepEqual(race.map(r=>r.status).sort(),[200,409]);
    assert.equal((await bob.browser.mutate('POST',route,intent('🇻🇳',0))).status,200);
    const removed=await alice.browser.mutate('DELETE',`/api/messages/${original.storageId}`);assert.equal(removed.status,200);
    const snapshot=await bob.browser.request(`/api/conversations/${conversationId}/reactions?ids=${original.storageId}`);
    assert.equal(snapshot.body.items[0].state,'deleted');assert.deepEqual(snapshot.body.items[0].actors,[]);
    assert.equal((await bob.browser.mutate('POST',route,intent('👍',1))).status,404);
    assert.equal((await alice.browser.mutate('POST',route,same)).status,404);
    assert.deepEqual((await stack.history(alice,conversationId)).items,[removed.body.message]);
  });
  test('unauthorized, forged, invalid emoji and blocked requests do not mutate metadata or notify stale grants',async()=>{
    const {alice,bob,conversationId,epoch}=await stack.pair('auth-a','auth-b'),stranger=await stack.person('outsider');
    const m=(await alice.browser.mutate('POST',`/api/conversations/${conversationId}/messages`,await stack.envelope(alice,conversationId,epoch,'Do not expose plaintext'))).body.message;
    const route=`/api/messages/${m.storageId}/reaction`,anonymous=new Browser(stack.url);
    assert.equal((await anonymous.request(route,{method:'POST',body:intent('👍',0)})).status,401);
    assert.equal((await alice.browser.request(route,{method:'POST',body:intent('👍',0)})).status,403);
    assert.equal((await stranger.browser.mutate('POST',route,intent('👍',0))).status,404);
    assert.equal((await stranger.browser.request(`/api/conversations/${conversationId}/reactions?ids=${m.storageId}`)).status,404);
    for(const emoji of ['private text','👍👍','1','\u200d','🇻','👍\n'])assert.equal((await alice.browser.mutate('POST',route,intent(emoji,0))).status,400);
    assert.equal((await alice.browser.mutate('POST',route,{...intent('👍',0),userId:bob.id})).status,400);
    const socket=await stack.connect(bob),mark=socket.mark();await alice.browser.mutate('POST','/api/blocks',{userId:bob.id});
    assert.equal((await bob.browser.mutate('POST',route,intent('👍',0))).status,404);
    assert.equal(await stack.bridge.realtime.notifyReactionsChanged(conversationId,m.id),0);
    await delay(100);assert.equal(socket.events('message:reactions-changed',mark).length,0);
  });
});
